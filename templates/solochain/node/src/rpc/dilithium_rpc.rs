#[rpc(server)]
pub trait DilithiumApi {
    #[method(name = "dilithium_verify")]
    fn verify_signature(&self, message: Vec<u8>, signature: Vec<u8>) -> RpcResult<bool>;
}

pub struct Dilithium {}

impl Dilithium {
    pub fn new() -> Self {
        Self {}
    }
}

impl DilithiumApiServer for Dilithium {
    fn verify_signature(&self, message: Vec<u8>, signature: Vec<u8>) -> RpcResult<bool> {
        // Log de entrada
        log::info!("🔑 Dilithium RPC called: verify_signature");


        let signature_obj = <DilithiumDetachedSignature as DetachedSignatureTrait>::from_bytes(&signature)
            .map_err(|e| {
                log::error!("❌ Invalid signature: {:?}", e);
                ErrorObject::owned(1, "Invalid signature", None::<()>)
            })?;

        log::debug!("✅ Signature object created successfully");

        let pubkey_obj = <DilithiumPublicKey as PublicKeyTrait>::from_bytes(&DILITHIUM_PUB_KEY)
            .map_err(|e| {
                log::error!("❌ Invalid public key: {:?}", e);
                ErrorObject::owned(2, "Invalid pubkey", None::<()>)
            })?;

        log::debug!("✅ Public key object created successfully");

        let is_valid = verify_detached_signature(&signature_obj, &message, &pubkey_obj).is_ok();

        if is_valid {
            log::info!("✅ Signature verification: SUCCESS");
        } else {
            log::warn!("⚠️ Signature verification: FAILED");
        }

        Ok(is_valid)
    }
}
